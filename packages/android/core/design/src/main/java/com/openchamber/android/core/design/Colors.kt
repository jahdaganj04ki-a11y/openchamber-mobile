package com.openchamber.android.core.design

import androidx.compose.ui.graphics.Color

/**
 * The colors the shared themes define.
 *
 * The desktop and the phone read the same theme files, so the two clients
 * look the same. The values here are the default OpenChamber theme, and the
 * syntax palette that goes with it.
 */
data class OpenChamberColors(
    val primary: Color,
    val primaryHover: Color,
    val background: Color,
    val foreground: Color,
    val muted: Color,
    val mutedForeground: Color,
    val elevated: Color,
    val subtle: Color,
    val border: Color,
    val borderHover: Color,
    val selection: Color,
    val focusRing: Color,
    val hover: Color,
    val active: Color,
    val error: Color,
    val warning: Color,
    val success: Color,
    val info: Color,
    val userMessageBackground: Color,
    val divider: Color,
    val link: Color,
    val linkHover: Color,
    val inlineCode: Color,
    val inlineCodeBackground: Color,
    val blockquote: Color,
    val blockquoteBorder: Color,
    val listMarker: Color,
    val bold: Color,
    val italic: Color,
    val syntax: SyntaxColors,
)

data class SyntaxColors(
    val background: Color,
    val comment: Color,
    val keyword: Color,
    val string: Color,
    val number: Color,
    val function: Color,
    val variable: Color,
    val type: Color,
    val operator: Color,
    val variableProperty: Color,
    val className: Color,
    val punctuation: Color,
    val diffAdded: Color,
    val diffRemoved: Color,
    val diffModified: Color,
)

